/**
 * coverLetter.js — генерация сопроводительного письма под конкретную вакансию.
 *
 * Обобщено из личного hhorosho (тот промпт был жёстко про одного человека — Тимофея,
 * его стек, его github). Здесь та же СТРАТЕГИЯ (сильные стороны — уверенно, даже если
 * вакансия называет технологию не по имени в резюме; честные пробелы — только явно
 * названные, без самоуничижения — 99% скрининга на hh.ru сейчас автоматическое, и
 * рефлекторное хеджирование читается фильтром как слабость, а не честность), но
 * параметризована профилем арендатора, а не одним человеком.
 *
 * @typedef {Object} TenantProfile
 * @property {string} fullName
 * @property {string[]} strongStack — области, где НЕ хеджируем ("JavaScript/TypeScript
 *   (Node.js, React, Vue, ...)", "Python", "Kubernetes"...)
 * @property {string[]} honestGaps — области, где признаём пробел прямо, но без
 *   самоуничижения ("PHP", "C++")
 * @property {{domain: string, canonical: string}=} portfolioLink — например
 *   { domain: "github.com", canonical: "github.com/handle" }
 */

const { toPlainText } = require('./plainText');
const { stripAssistantLeak } = require('./assistantLeak');

// Письмо короче этого после вырезания служебного хвоста — значит модель писала не письмо.
const MIN_LETTER_CHARS = 300;

function buildSystemPrompt(profile) {
  // Стек в настройках не задан (или там была заглушка вроде «Собери сам» — её убирает
  // cleanProfileList): уверенно говорим обо всём, что есть в самом резюме.
  const strongList = profile.strongStack.join(', ') || 'всё, что указано в резюме (его технологии и навыки)';
  const gapsList = profile.honestGaps.length ? profile.honestGaps.join(', ') : null;

  // Имя может не дойти: в профиле оно необязательное, а раньше сюда вообще не
  // прокидывалось — и в подпись уходило буквальное "undefined". Резюме с hh.ru
  // всегда начинается с ФИО, поэтому пустое имя не ломает письмо: модель берёт
  // имя из резюме, которое лежит в пользовательской части промпта.
  const fullName = String(profile.fullName || '').trim();
  const signatureRule = fullName
    ? `подпись "С уважением, ${fullName}"`
    : 'подпись "С уважением, <имя из резюме>" — возьми имя и фамилию из блока РЕЗЮМЕ выше '
      + 'ровно как они там написаны, ничего не выдумывай. Плейсхолдеров в письме быть не должно';
  const linkLine = profile.portfolioLink
    ? `- Финал: готовность созвониться/показать код на ${profile.portfolioLink.canonical}, ${signatureRule}.`
    : `- Финал: готовность созвониться, ${signatureRule}.`;

  return `Ты пишешь сопроводительные письма от лица ${fullName || 'автора резюме'} в его/её собственном
голосе: конкретика по фактам из резюме, честность без самоуничижения, без канцелярита
и без общих фраз ("командный игрок", "быстро обучаюсь", "стрессоустойчив") без факта за ними.

СТЕК — где уверенно, а где честно признаём пробел (это разграничение критично, не путай):

Сильный стек — здесь НЕ хеджируем и не сравниваем себя в невыгодную сторону, даже если
конкретная вакансия называет технологию, которая буквально не упомянута в резюме: ${strongList}.
Если вакансия просит что-то из смежной области внутри этого списка, чего нет буквально в
резюме — пиши прямо и уверенно, что владеешь: для инженера с таким бэкграундом это не разрыв
в компетенции, а вопрос синтаксиса конкретного API, не пиши "меньше опыта"/"не пробовал" про
вещи из этого списка.

ЖЁСТКАЯ ГРАНИЦА (нарушать нельзя): уверенность распространяется ТОЛЬКО на смежные инструменты
ВНУТРИ экосистемы кандидата — соседние библиотеки/фреймворки того же языка, смежные БД,
DevOps-инструменты. НИКОГДА не заявляй владение ЧУЖИМ основным языком программирования, которого
нет в резюме (например PHP, 1С, Java, C#, Ruby, если резюме про Node/TS/Go/Python). Фраза вроде
"отлично владею PHP и Laravel" при резюме без PHP — прямая ложь, она подрывает доверие и
недопустима. Если основной язык вакансии чужой — не пиши, что им владеешь; честно опирайся на
переносимый опыт (архитектура, БД, нагрузка), не приписывая себе чужой язык.

${gapsList ? `Честный пробел — ТОЛЬКО: ${gapsList}. Если вакансия требует именно это как основной навык — можно признать прямо, но без самоуничижения: не "я не умею", а в духе "не основной стек, но с таким бэкграундом освоение нового — вопрос времени, не барьер".` : 'Честных пробелов в профиле не указано — если вакансия просит что-то совсем незнакомое, отвечай честно и нейтрально, без хвастовства и без самоуничижения.'}

Почему это важно: в большинстве случаев первичный отсев вакансии делает не человек, а
автоматический скоринг/ИИ по ключевым словам и явным признакам неуверенности в тексте —
письмо должно честно, но максимально уверенно закрывать формальные требования, не создавать
искусственную слабость там, где её объективно нет.

Правила:
- Пиши от первого лица, по-русски (если вакансия явно на другом языке — на нём же).
- Первый абзац — конкретно про ЭТУ вакансию/компанию, что зацепило (не шаблонное вступление).
- Дальше — конкретные факты из резюме, которые реально закрывают требования вакансии.
  Не пересказывай резюме целиком, выбирай релевантное именно этой вакансии.
- Не выдумывай конкретные проекты/цифры, которых нет в резюме — уверенность про сильный стек
  не значит придумывать факты, значит не занижать реальные навыки.
${linkLine}
- ВАЖНО: только простой текст, без markdown — письмо идёт напрямую в текстовое поле сайта.
  НИКОГДА не оформляй ссылки как [текст](url) — пиши просто адрес, без квадратных скобок и
  без повторения ссылки дважды.
- Длина — 150-350 слов, не больше. Плотно, без воды.
- Контактов в письме не указывай (телефон, почта, Telegram, ники): работодатель видит их в резюме.
  Боты, каналы и сайты из резюме упоминай только как проекты, никогда как способ связи.
- Не пиши, что уже изучил сайт/видео/продукт компании, если это не следует из текста вакансии.

Письмо уйдёт работодателю ДОСЛОВНО, без чьей-либо проверки. Верни ТОЛЬКО само письмо: без
вступления перед ним и без приписок после подписи — никаких предложений адаптировать письмо
под другие вакансии, подготовить другие варианты и т.п. Это разговор с тем, кто заказал текст,
а читать его будет работодатель.`;
}

function buildUserPrompt({
  resumeText, vacancyTitle, company, vacancyDescription, salaryUnspecified, expectedSalaryText,
}) {
  const parts = [
    `РЕЗЮМЕ (актуальный текст с hh.ru):`,
    resumeText,
    '',
    `ВАКАНСИЯ: ${vacancyTitle} — ${company}`,
    `ОПИСАНИЕ ВАКАНСИИ:`,
    vacancyDescription,
  ];

  // Зарплата в вакансии не указана — по просьбе кандидата письмо должно это мягко
  // отметить: одно вежливое предложение ближе к концу, без ультиматумов, с ориентиром
  // по доходу, если он известен. Так работодатель сразу видит вилку кандидата и не
  // тратит первый контакт на «а сколько вы хотите».
  if (salaryUnspecified) {
    parts.push(
      '',
      'ЗАРПЛАТА: в этой вакансии уровень дохода НЕ указан. Добавь в письмо одно короткое '
      + 'вежливое предложение об этом — попроси уточнить вилку/уровень дохода'
      + (expectedSalaryText
        ? `, и назови ориентир кандидата: рассматриваю предложения от ${expectedSalaryText}.`
        : '.')
      + ' Не первым абзацем, ближе к концу, без ультиматумов и без пафоса — это обычная деловая ремарка.',
    );
  }

  return parts.join('\n');
}

/**
 * @param {{ resumeText: string, vacancyTitle: string, company: string, vacancyDescription: string }} vacancy
 * @param {TenantProfile} profile
 * @param {{ ask: Function }} llmClient
 */
/**
 * Последний рубеж: в подпись не должно попасть служебное слово или плейсхолдер.
 * Письмо уходит работодателю без глаз человека, и «С уважением, undefined» стоит
 * дороже любого другого дефекта в тексте — поэтому чистим уже готовый результат,
 * не полагаясь на то, что промпт всегда отработает как задумано.
 */
// После подписи в письме не бывает ничего. Живой случай: за «С уважением, Имя» ушла приписка
// «Если нужно скорректировать детали… дайте знать, и я перепишу текст под новые вводные» —
// разговор с заказчиком текста. Режем всё после строки подписи (и строки имени, если подпись
// разбита на две строки).
function cutAfterSignature(text) {
  const t = String(text || '');
  const re = /С уважением[^\n]*/gi;
  let m; let last = null;
  while ((m = re.exec(t)) !== null) last = m;
  if (!last) return t;
  let end = last.index + last[0].length;
  const lineRest = last[0].replace(/С уважением,?/i, '').trim();
  if (!lineRest) {
    const next = t.slice(end).match(/^\s*\n([^\n]{2,60})/);
    if (next) end += next[0].length;
  }
  return t.slice(0, end).trim();
}

function fixSignature(text, fullName) {
  const broken = /С уважением,?\s*(undefined|null|ИМЯ_ИЗ_РЕЗЮМЕ|<[^>\n]*>|\[[^\]\n]*\])\s*\.?/gi;
  return text.replace(broken, fullName ? `С уважением, ${fullName}` : 'С уважением');
}

async function generateCoverLetter(vacancy, profile, llmClient) {
  const canonicalLinks = profile.portfolioLink ? { [profile.portfolioLink.domain]: profile.portfolioLink.canonical } : {};
  const fullName = String(profile.fullName || '').trim();

  for (let attempt = 1; attempt <= 2; attempt += 1) {
    const { text } = await llmClient.ask(
      buildSystemPrompt(profile),
      attempt === 1 ? buildUserPrompt(vacancy)
        : `${buildUserPrompt(vacancy)}\n\nВАЖНО: верни только само письмо работодателю, без приписок для заказчика текста.`,
      { timeoutMs: 300000, kind: 'cover_letter' },
    );
    // Живой случай: письмо ушло работодателю с припиской «Если нужно адаптировать это
    // письмо под другие вакансии, присылайте их описание — я подготовлю новые варианты».
    let letter = stripAssistantLeak(toPlainText(text, { canonicalLinks })).text;
    if (letter.length < MIN_LETTER_CHARS) continue;
    // Если служебная фраза стояла ДО подписи, подпись срезалась вместе с хвостом.
    if (fullName && !/С уважением/i.test(letter)) letter = `${letter}\n\nС уважением, ${fullName}`;
    return fixSignature(cutAfterSignature(letter), fullName);
  }
  throw new Error('LLM дважды не написал пригодное письмо — не отправляю');
}

module.exports = { generateCoverLetter, buildSystemPrompt, fixSignature, cutAfterSignature };
