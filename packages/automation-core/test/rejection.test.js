// Отказ — единственный повод промолчать в переписке. Живой промах 06.10.2026: письмо
// «приняли решение пока не продолжать процесс» и следом метка hh «Отказ» — а ИИ ответил
// «буду ждать результатов рассмотрения моей кандидатуры».
const test = require('node:test');
const assert = require('node:assert');
const { looksLikeRejection, rejectedInTail, employerTail, classifyEmployerMessage } = require('../src/employerMessage');

const LIVE = `Спасибо большое за ваше время, интерес к нашей вакансии и участие в процессе отбора.

Мы внимательно ознакомились с вашим опытом и проектами. После обсуждения внутри команды мы приняли решение пока не продолжать процесс по позиции AI Engineer.

В первую очередь это связано с тем, что сейчас мы ищем специалиста с более продолжительным опытом работы над AI-продуктами в коммерческой среде.

При этом у нас осталось хорошее впечатление от вашего интереса к AI. Поэтому надеемся, что наши пути ещё пересекутся в будущем.`;

test('отказы узнаём', () => {
  for (const t of [LIVE, 'Отказ', 'ВикторОтказ', 'ЕленаОтказТимофей Игоревич, здравствуйте! Большое спасибо за интерес',
    'Отказ\nСпасибо за отклик', 'Мы решили не двигаться дальше с вашей кандидатурой.',
    'Команда решила пока не продолжать.', 'Сейчас не готовы пока продолжить общение.',
    'Сохраним ваше резюме в кадровом резерве.', 'Надеемся, наши пути еще пересекутся!',
    'АлександрОтказ.', 'ArtemОтказТимофей Игоревич, здравствуйте! Большое спасибо']) {
    assert.ok(looksLikeRejection(t), t);
    assert.equal(classifyEmployerMessage(t).kind, 'rejection', t);
  }
});

test('обычные сообщения — не отказ', () => {
  for (const t of ['Расскажите о своём опыте с Kafka', 'Если вы решили не продолжать — просто напишите.',
    'Отказ от ответственности: тестовое оплачивается', 'Был ли у вас отказ от оффера?',
    'Спасибо за отклик, мы рассмотрим ваше резюме', 'Приглашаем вас на собеседование',
    'Мы приняли решение пригласить вас на следующий этап']) {
    assert.ok(!looksLikeRejection(t), t);
  }
});

test('отказ в хвосте: письмо, потом метка hh', () => {
  const msgs = [
    { from: 'ai', text: 'Здравствуйте! Откликнулся на вакансию.' },
    { from: 'employer', text: LIVE },
    { from: 'employer', text: 'Отказ' },
  ];
  assert.ok(rejectedInTail(msgs));
  assert.ok(rejectedInTail([...msgs.slice(0, 2), { from: 'employer', text: 'Удачи вам!' }]));
});

test('после нашего ответа или приглашения отказ в хвосте не считается', () => {
  assert.ok(!rejectedInTail([
    { from: 'employer', text: 'Отказ' },
    { from: 'ai', text: 'Спасибо!' },
    { from: 'employer', text: 'Извините, ошиблись. Расскажите о проекте?' },
  ]));
  assert.ok(!rejectedInTail([
    { from: 'employer', text: 'Отказ' },
    { from: 'employer', text: 'Простите, ошибка! Приглашаем вас на собеседование, когда вам удобно созвониться?' },
  ]));
});

// Служебные строки chatik не должны попадать в тред как реплики: живой тред кончался на
// «Непрочитанные сообщения» от работодателя, а «Сегодня» числилось нашим ответом.
const { isChatChrome } = require('../src/hh/negotiations');

test('даты и кнопки chatik — не сообщения', () => {
  for (const t of ['Сегодня', 'Вчера', '2 октября', '27 сентября', '1 января 2027', 'Непрочитанные сообщения',
    'Добавить сопроводительное', 'Без сопроводительного письма', ' Сегодня ']) {
    assert.ok(isChatChrome(t), t);
  }
  for (const t of ['Сегодня смогу', 'Да', 'Отказ', 'ОтказДанилевич Виктор', '2 октября в 10:00 удобно?', 'Вчера созванивались']) {
    assert.ok(!isChatChrome(t), t);
  }
});

test('живой тред 06.10.2026 без служебных строк кончается отказом', () => {
  const scraped = [
    { from: 'employer', text: 'Викторотлично, приглашение будет на почте' },
    { from: 'ai', text: 'Сегодня' },
    { from: 'ai', text: '(Прошу прощения, AI-ассистент сработал автоматически. Вчера созванивались, буду ждать ОС)' },
    { from: 'employer', text: 'Непрочитанные сообщения' },
    { from: 'employer', text: 'ОтказДанилевич Виктор' },
  ].filter((m) => !isChatChrome(m.text));
  assert.equal(scraped.length, 3);
  assert.equal(classifyEmployerMessage(scraped[scraped.length - 1].text).kind, 'rejection');
  assert.ok(rejectedInTail(scraped));
});

test('хвост работодателя — всё после нашего последнего сообщения', () => {
  const msgs = [{ from: 'employer', text: 'а' }, { from: 'ai', text: 'б' }, { from: 'employer', text: 'в' }, { from: 'employer', text: 'г' }];
  assert.deepEqual(employerTail(msgs).map((m) => m.text), ['в', 'г']);
  assert.deepEqual(employerTail([...msgs, { from: 'ai', text: 'д' }]), []);
});
