// Разговор о времени созвона ведёт только человек. Ловим широко (цена промаха — созвон,
// о котором кандидат не знает), но номера версий вроде «Node.js 18.20» похожи на время —
// обычный вопрос с ними не должен уходить человеку.
const test = require('node:test');
const assert = require('node:assert');
const { looksLikeScheduling } = require('../src/employerMessage');

test('время созвона уходит человеку', () => {
  for (const t of ['Когда Вам удобно созвониться по зуму на полчаса?', 'Сегодня в 19:00 по Москве удобно?',
    'Завтра в 15:00 подойдёт?', 'Можем перенести на четверг?', 'Какое время вам удобно?',
    'Приглашаем вас на собеседование', 'Ссылка на встречу: https://telemost.yandex.ru/j/123',
    'Подтверждаю встречу на 14:30', 'Какие слоты у вас свободны на этой неделе?',
    // Живой промах: ни «созвона», ни «удобно» — и ИИ ответил за человека.
    'Тимофей, благодарю за развернутый ответ. Завтра с 9:00 до 12:00 есть возможность?',
    'В пятницу в 15.00 актуально?']) {
    assert.ok(looksLikeScheduling(t), t);
  }
});

test('обычные вопросы остаются ИИ', () => {
  for (const t of ['Расскажите о своём опыте с Kafka', 'Какая у вас зарплатная вилка?',
    'Спасибо за отклик, мы рассмотрим ваше резюме', 'Опыт от 3 лет, стек Node.js 18.20',
    'Мы используем Python 3.11 и Django', 'Готовы ли вы к переезду?',
    'Какие среды разработки используете?', 'Какой у вас опыт с Node.js 18.20?']) {
    assert.ok(!looksLikeScheduling(t), t);
  }
});
