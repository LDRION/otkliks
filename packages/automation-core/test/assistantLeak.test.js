// Фильтр служебного текста целиком на регулярках, а в JS \b и \w не видят кириллицу —
// на этом уже спотыкались. Реальные утечки из переписки и честные фразы AI-инженера,
// которые трогать нельзя.
const test = require('node:test');
const assert = require('node:assert');
const { stripAssistantLeak, employerUsesTy } = require('../src/assistantLeak');
const { looksLikeAiSuspicion } = require('../src/employerMessage');

test('режет реальные утечки по первой служебной фразе', () => {
  const invite = stripAssistantLeak('Отлично, было бы здорово созвониться! Уточню своё расписание и напишу удобное время сегодня.\n'
    + 'Я отправил первое подтверждение приглашения. По правилам, сейчас мне нужно прислать второе сообщение.\n'
    + 'Напиши мне, какие дни и часы тебе удобны, и я сформулирую готовый ответ для работодателя.');
  assert.strictEqual(invite.text, 'Отлично, было бы здорово созвониться! Уточню своё расписание и напишу удобное время сегодня.');

  const letter = stripAssistantLeak('Готов показать код на github.com/LDRION\nС уважением, Тимофей Коньшин\n'
    + 'Если нужно адаптировать это письмо под другие вакансии, присылайте их описание — я подготовлю новые варианты.');
  assert.ok(letter.text.endsWith('С уважением, Тимофей Коньшин'));

  const tail = stripAssistantLeak('Буду рад обсудить детали голосом.\nЕсли нужно скорректировать время, дай знать.');
  assert.strictEqual(tail.text, 'Буду рад обсудить детали голосом.');

  const header = stripAssistantLeak('Вот вариант ответа работодателю:\nЗдравствуйте! Опыт с PostgreSQL больше 4 лет.');
  assert.strictEqual(header.text, 'Здравствуйте! Опыт с PostgreSQL больше 4 лет.');
});

test('каждый шаблон работает сам по себе, окончания кириллицей', () => {
  for (const t of ['Согласно инструкции, подтверждаю.', 'Это второе сообщение.', 'Сообщение для работодателя готово.',
    'Могу адаптировать это письмо.', 'Подготовлю другие версии.', 'Сформулирую новый ответ для работодателя.',
    'Это черновик сообщения.', 'Варианты письма могу сократить.', 'По правилу сначала подтверждаю.']) {
    assert.strictEqual(stripAssistantLeak(`Здравствуйте! ${t}`).text, 'Здравствуйте!', t);
  }
});

test('не трогает честный текст, в том числе про ИИ и боты', () => {
  for (const t of ['Если нужно скорректировать время, дайте знать — подстроюсь.',
    'Я отправил вам резюме на почту.', 'На прошлом месте работодатель внедрял микросервисы.',
    'Следующим сообщением пришлю ссылку на репозиторий.',
    'Настраивал шаблоны ответов для чат-бота и систему автоответов на базе LLM.',
    'Генерировал варианты ответов через GPT-4 и Claude.', 'Как AI/LLM-инженер проектировал промпт-контуры.',
    'Работаю по правилу трёх коммитов в день.', 'Веду разработку по правилам чистой архитектуры.']) {
    assert.deepStrictEqual(stripAssistantLeak(t), { text: t, leaked: false, dropped: '' }, t);
  }
});

test('«ты» законно, когда работодатель сам на «ты»', () => {
  const allowTy = employerUsesTy([{ from: 'employer', text: 'Привет! Напиши, когда удобно?' }]);
  assert.ok(allowTy);
  assert.strictEqual(stripAssistantLeak('Давай завтра, напиши время.', { allowTy }).leaked, false);
  assert.strictEqual(stripAssistantLeak('Здравствуйте! Напиши мне время.').leaked, true);
});

test('подозрение «это ИИ» ловится, разговор про ИИ по делу — нет', () => {
  for (const t of ['Тимофей) это ИИ сообщение, не совсем поняла Вас', 'Вы бот?', 'Мне кажется, мне отвечает нейросеть',
    'Это сообщение написано ChatGPT?', 'Ответ сгенерирован ИИ, да?',
    'ИИ интересно тут работает 😜']) assert.ok(looksLikeAiSuspicion(t), t);
  for (const t of ['Расскажите про опыт с ИИ', 'Вы ИИ-инженер или бэкендер?', 'Нужно разрабатывать чат-бота',
    'Это автоматическое сообщение, не отвечайте на него', 'Мы делаем бота для ответов клиентам',
    'У нас AI-продукт для ритейла: строим рекомендательную систему, и ИИ работает в проде уже два года, нужна помощь с RAG.']) {
    assert.ok(!looksLikeAiSuspicion(t), t);
  }
});
