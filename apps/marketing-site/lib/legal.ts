import type { ReactNode } from 'react';
import { createElement } from 'react';

// Реквизиты исполнителя — в одном месте, подставляются и в оферту, и в политику.
//
// Статус: самозанятый (плательщик налога на профессиональный доход). Это законный
// способ принимать оплату от физлиц; чек по каждому платежу формируется в приложении
// «Мой налог».
//
// ФИО и ИНН публикуются намеренно: без них оферта не позволяет однозначно определить
// сторону договора. Эти же данные уходят клиенту в чеке «Мой налог», а статус НПД по
// ИНН проверяется публично на сервисе ФНС — ничего сверх того здесь не раскрыто.
// Паспортным данным, СНИЛС, адресу и счёту в этом файле не место.
export const LEGAL = {
  /** Фамилия Имя Отчество полностью, как в паспорте */
  fullName: 'Коньшин Тимофей Игоревич',
  /** ИНН самозанятого, 12 цифр (контрольные разряды проверены) */
  inn: '420552798657',
  /** Дата редакции документов — меняем при каждом существенном изменении текста */
  updated: '29 сентября 2026',
  /** Почта для юридически значимых обращений */
  email: 'support@otkliks.ru',
  /** Реквизиты заполнены и документы можно считать полными */
  get filled() {
    return Boolean(this.fullName && this.inn);
  },
};

/**
 * Строка с реквизитами исполнителя. Пока ФИО и ИНН не заданы — выводит статус без
 * выдуманных данных, чтобы на живом сайте не оказалось текста-заглушки вида «[ИНН]».
 */
export function LegalRequisites({ withEmail = false }: { withEmail?: boolean }): ReactNode {
  const parts = LEGAL.filled
    ? `${LEGAL.fullName}, самозанятый (плательщик налога на профессиональный доход), ИНН ${LEGAL.inn}`
    : 'самозанятый исполнитель (плательщик налога на профессиональный доход), владелец сервиса «Откликс»';
  return createElement(
    'span',
    null,
    parts,
    withEmail ? `, адрес для обращений: ${LEGAL.email}` : null,
  );
}
