/**
 * aiErrorText.js — служебный текст провайдера ИИ, пришедший вместо ответа.
 *
 * Siberi AI снимает ответ со страницы провайдера в браузере, и когда провайдер отказывает,
 * его сообщение об отказе возвращается как РЕЗУЛЬТАТ задачи со статусом «выполнено». Такое
 * нельзя ни отправлять работодателю, ни разбирать как ответ модели. Живые случаи:
 *  - Mistral под нагрузкой: «Что-то пошло не так. Искусственному интеллекту не удалось
 *    создать ответ.»;
 *  - квота провайдера: «Вы исчерпали лимит на ответы от ИИ. Повторите попытку позже.» —
 *    97 таких «успешных» задач за двое суток, одна ушла работодателю в чат.
 *
 * Шаблоны узкие, по формулировкам самих провайдеров. Кандидат — AI/LLM-инженер и честно
 * пишет про rate limiting и квоты API, поэтому общие слова («rate limit», «лимит
 * запросов») не ловим. Служебные сообщения короткие — длинный текст с такой фразой внутри
 * почти наверняка настоящий ответ.
 *
 * Копии: apps/core-api/src/lib/siberiClient.js и apps/marketing-site/lib/siberiClient.ts
 * (свои пакеты, без зависимости от automation-core) — менять синхронно.
 */
function isAiErrorText(text) {
  const t = String(text || '').trim();
  if (!t) return false;
  if (/не удалось (?:создать|сгенерировать|получить) ответ/i.test(t)) return true;
  if (/Искусственному интеллекту не удалось/i.test(t)) return true;
  if (/лимит\s+на\s+(?:ответы|запросы|сообщения)\s+(?:от\s+)?(?:ии|ai|нейросети)/i.test(t)) return true;
  if (t.length > 300) return false;
  if (/(?:^|[\s—-])Что-то пошло не так/i.test(t)) return true;
  if (/исчерпал[аи]?\s+(?:[а-яё]+\s+)?лимит/i.test(t)) return true;
  if (/повторите попытку позже/i.test(t)) return true;
  if (/you(?:'ve| have) (?:reached|exceeded|hit) (?:your|the)[^.]{0,30}limit|quota (?:exceeded|reached)|too many requests|try again later/i.test(t)) return true;
  return false;
}

module.exports = { isAiErrorText };
