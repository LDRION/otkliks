// Ручной пол зарплаты из настроек лаунчера (profile.minSalary) — то же поле, что задаёт
// нижнюю границу для фильтра вакансий и текста сопроводительного письма (см. applyJob.js).
// Раньше сюда не долетало вовсе: реплики в чате формировались только из resumeText, а на
// hh.ru лежат резюме с РАЗНЫМИ цифрами (у кандидата их может быть несколько, каждое со
// своей желаемой зарплатой) — стоило поменять пол в настройках, старое число из текста
// резюме, использованного при отклике, продолжало всплывать в переписке. Настройка в
// лаунчере — то, что человек только что осознанно поменял, поэтому она приоритетнее.
function formatMinSalary(profile) {
  const minSalary = profile && profile.minSalary;
  if (!minSalary || !(Number(minSalary.amount) > 0)) return '';
  return formatSalary(Number(minSalary.amount), minSalary.currency || 'RUB');
}

// Скриптовый скрининг-бот hh.ru («Робот-рекрутер») — не человек и не LLM: простой парсер,
// один вопрос за раз. Живой тест на реальном чате: короткий прямой ответ бот принимает и
// идёт к следующему вопросу; наш обычный стиль (дисклеймер + довесок "когда вам удобно
// созвониться?") он не разбирает — переспрашивает по кругу и в итоге перезапускает весь
// опрос с начала. Обычные правила (цель — созвон, тон, длина) здесь неприменимы: боту
// нечего "убеждать", он не читает нюансы, ему нужен только факт.
