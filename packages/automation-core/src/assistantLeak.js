/**
 * assistantLeak.js — ловит в сгенерированном тексте реплики, обращённые НЕ к работодателю.
 *
 * Siberi AI гоняет запросы через чат-ассистентов (Le Chat и т.п.), а они по привычке
 * разговаривают с тем, кто их спросил: дописывают «если нужно адаптировать это письмо под
 * другие вакансии — присылайте», пересказывают правила из промпта («по правилам, сейчас
 * мне нужно прислать второе сообщение»), спрашивают кандидата «напиши мне, какие дни тебе
 * удобны». Всё это уходило работодателю дословно — живой случай: рекрутер ответила «это ИИ
 * сообщение, не совсем поняла Вас».
 *
 * Промпт это только снижает, но не исключает, поэтому здесь последний рубеж. Режем по
 * ПЕРВОЙ служебной фразе и всё после неё: сменив адресата, модель обычно уже не
 * возвращается к работодателю, и хвост целиком служебный — в том числе фразы, которые ни
 * один шаблон ниже не узнал бы. Шаблоны нарочно узкие: кандидат — AI/LLM-инженер, и про
 * ИИ, ботов и автоответы он честно пишет в самих письмах; такие слова здесь не ловим.
 */

const META_PATTERNS = [
  // Пересказ правил и собственных шагов.
  // «По правилам, сейчас мне нужно…» — но не «по правилам чистой архитектуры».
  /по правил(?:ам|у),?\s+(?:сейчас|теперь|сначала|мне|я)(?![а-яё])|согласно (?:правилам|инструкци)|по (?:моей |этой |твоей |вашей )?инструкци/i,
  /(?:перв|втор)(?:ое|ым|ого) (?:сообщени|подтвержден)/i,
  // Работодатель в третьем лице — как получатель текста, а не собеседник.
  /(?:для|к) работодател|работодателю (?:можно|нужно|стоит|отправ|напис|ответ|передат)/i,
  /(?:ответ|сообщени|письм)[а-яёa-z]* (?:для |к )?работодател/i,
  // Предложение доработать сам текст — это разговор с заказчиком текста.
  /адаптир[а-яёa-z]* (?:это |данное |мо[её] |ваше |твоё |твое )?(?:письм|сообщени|ответ|текст)/i,
  /под (?:другие|другую|остальные|следующие|новые) ваканси/i,
  /подготов[а-яёa-z]* (?:новые |другие |ещё |еще |несколько )?(?:вариант|верси)/i,
  /(?:сформулир|состав|подготов)[а-яёa-z]* (?:готов[а-яёa-z]* |нов[а-яёa-z]* |финальн[а-яёa-z]* )?(?:ответ|текст|письм|сообщени)[а-яёa-z]* (?:для|под|работодател)/i,
  /(?:вариант|версия|черновик)[а-яёa-z]* (?:ответа|письма|сообщения|текста)(?![а-яё])/i,
  // «…дайте знать, и я перепишу текст под новые вводные» — живой случай в конце письма.
  /перепиш[а-яё]*\s+(?:этот |данный |мой )?(?:текст|письм|сообщени|ответ)/i,
  /под нов(?:ые|ую|ыми) вводн/i,
  // «Если вы хотите, чтобы я скорректировал ответ, уточните:» + «Требуется ли изменить тон
  // сообщения?» — живой случай 26.09.2026 (дальше шли вопросы кандидату про сам текст).
  // Узко, про сам текст сообщения: у копирайтера или редактора «стиль письма», «тон
  // сообщений бренда», «скорректирую тексты сайта» — законные слова в письме.
  /скорректир[а-яё]*\s+(?:этот |данный |мой |свой |сам )?(?:ответ|текст|письмо|сообщение|формулировк[а-яё]*)(?![а-яё])/i,
  /чтобы я\s+(?:скорректир|измени|поправ|доработ|перепис|сократ|дополн|адаптир|передела|переформулир)[а-яё]*\s+(?:[а-яё]+\s+)?(?:ответ|текст|письмо|сообщение|формулировк|вступлени|тон)/i,
  /(?:изменить|поменять|сменить|смягчить|ужесточить|скорректировать|подправить)\s+тон(?![а-яё])/i,
  /тон\s+(?:этого\s+|данного\s+)?(?:сообщения|ответа)(?![а-яё])/i,
  /(?:сделать|сократить)\s+(?:(?:этот|данный|мой)\s+(?:текст|письмо|сообщение)|ответ|сообщение)\s+(?:короче|длиннее|формальнее|официальнее|мягче)/i,
];

// Обращение на «ты» к самому кандидату. С работодателем кандидат на «вы», так что в
// исходящем тексте это почти всегда модель, говорящая с заказчиком. Исключение —
// работодатель сам общается на «ты»: тогда правило выключается (allowTy).
const TY_RE = /(?:^|[^а-яё])(?:ты|тебе|тебя|тобой|твой|твоя|твоё|твое|твои|твоих|твоим|твоей|твоему|напиши|пришли|скажи|сообщи|уточни|подскажи|выбери|посмотри|проверь|дай знать|дай мне знать)(?![а-яё])/i;

// Заголовок-преамбула первой строкой: «Вот вариант ответа:», «Ответ работодателю:».
const HEADER_RE = /^\s*(?:(?:вот|ниже)(?![а-яё])[^\n]{0,60}|(?:готов(?:ый|ое|ая) )?(?:вариант|черновик|ответ|сообщение|письмо)(?: для)? работодател[а-яёa-z]*|(?:готов(?:ый|ое|ая) )(?:ответ|текст|письмо|вариант))\s*:\s*$/i;

function sentenceSpans(text) {
  const spans = [];
  let start = 0;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    const ends = ch === '\n' || (/[.!?…]/.test(ch) && (i + 1 >= text.length || /\s/.test(text[i + 1])));
    if (ends) {
      spans.push({ start, end: i + 1 });
      start = i + 1;
    }
  }
  if (start < text.length) spans.push({ start, end: text.length });
  return spans.filter((s) => text.slice(s.start, s.end).trim());
}

function isMeta(sentence, allowTy) {
  if (META_PATTERNS.some((re) => re.test(sentence))) return true;
  return !allowTy && TY_RE.test(sentence);
}

/** Пишет ли работодатель на «ты» — тогда «ты» в нашем ответе законно. */
function employerUsesTy(messages) {
  return (messages || []).some((m) => m && m.from === 'employer' && TY_RE.test(String(m.text || '')));
}

/**
 * @returns {{ text: string, leaked: boolean, dropped: string }}
 *   text — то, что можно отправлять (пустая строка, если спасать нечего);
 *   dropped — отрезанный хвост, для лога.
 */
function stripAssistantLeak(input, { allowTy = false } = {}) {
  let text = String(input || '').trim();
  let dropped = '';

  const firstNl = text.indexOf('\n');
  const firstLine = firstNl === -1 ? text : text.slice(0, firstNl);
  if (firstNl !== -1 && HEADER_RE.test(firstLine)) {
    dropped = firstLine.trim();
    text = text.slice(firstNl + 1).trim();
  }

  for (const s of sentenceSpans(text)) {
    if (isMeta(text.slice(s.start, s.end), allowTy)) {
      const tail = text.slice(s.start).trim();
      return {
        text: text.slice(0, s.start).trim(),
        leaked: true,
        dropped: dropped ? `${dropped} … ${tail}` : tail,
      };
    }
  }
  return { text, leaked: Boolean(dropped), dropped };
}

module.exports = { stripAssistantLeak, employerUsesTy, sentenceSpans };
