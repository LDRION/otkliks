/**
 * employerMessage.js — что именно написал работодатель и что с этим делать.
 *
 * Появилось вместе с двумя другими правками в переписке. Раньше «отвечать или нет»
 * решалось только по тому, кто написал последним, и после того как автопилот научился
 * отвечать на сообщения, пришедшие ДО первого снимка треда, он бы полез вежливо
 * отвечать и на отказы («мы не готовы пригласить вас на следующий этап») — то есть
 * тратить токены и выглядеть глупо там, где переписка уже закончена.
 *
 * Классифицируем дёшево, без LLM: формулировки у hh-скринеров типовые, а цена ошибки
 * несимметрична. Ошибочно промолчать на отказ — ничего не теряем; ошибочно ответить
 * на живой вопрос — теряем этап. Поэтому к 'rejection'/'ack' относим только явные
 * совпадения, всё сомнительное уходит в 'reply' — там дальше работает LLM.
 */

const REJECTION_PATTERNS = [
  // «не можем/не сможем/не готовы пригласить (вас) (на следующий этап)» и т.п. Именно это
  // раньше проходило как ПРИГЛАШЕНИЕ (система игнорировала «не» перед «можем»).
  /не (?:можем|сможем|готовы|будем|станем) (?:вас )?(?:пригласить|позвать|предложить|продолж|рассматрива)/i,
  /к сожалению[^.]{0,90}(?:не подош|не готов|не можем|не сможем|отказ|другого кандидата|остановили выбор|не соответству|не совсем соответству|двигаться дальше не)/i,
  // «ваш опыт не (совсем) соответствует нашим требованиям», «не соответствует вакансии/ожиданиям»
  /не (?:совсем |полностью |до конца )?соответству[а-я]*[^.!?\n]{0,45}(?:требован|ожидан|ваканс|позици|критери)/i,
  /(?:опыт|кандидатура|профиль|резюме|навыки)[^.!?\n]{0,45}не (?:совсем |полностью |до конца )?соответству/i,
  // Типовое закрытие отказа — рекрутеры так пишут ТОЛЬКО когда отказывают.
  /желаем (?:вам )?(?:успех|удач)[а-я]* (?:в поиске|в дальнейшем|в вашем|в трудоустройств|в карьер)/i,
  /вакансия (?:закрыта|уже закрыта|больше не актуальна)/i,
  /(?:выбрали|остановились на|отдали предпочтение) другому кандидату|(?:выбрали|остановились на) другом кандидате/i,
  /ваш отклик отклон/i,
  /не сможем предложить вам (?:работу|позицию|вакансию)/i,
  /вынуждены (?:вам )?отказать/i,
  // «Приняли решение пока не продолжать процесс», «мы решили не двигаться дальше». Живой
  // промах 06.10.2026: отказ без «к сожалению» и без «не можем пригласить» прошёл как
  // обычная реплика, и ИИ ответил «буду ждать результатов рассмотрения моей кандидатуры».
  // Подлежащее обязательно («приняли решение», «мы/команда решили»), иначе под шаблон
  // попал бы вопрос «если вы решили не продолжать — напишите».
  /(?:принял[аи]? решение|(?:мы|команда|компания) (?:[а-яё]+ )?решил[аи]?)[^.!?\n]{0,35}не (?:продолж|двигаться дальше|переходить к следующ)/i,
  /не (?:можем|сможем|готовы|будем|станем) (?:пока |сейчас |на данный момент |на этом этапе )(?:продолж|двигаться дальше|рассматрива)/i,
  // Типовые закрытия отказа: «надеемся, наши пути ещё пересекутся», «сохраним ваше резюме
  // в кадровом резерве».
  /наши пути (?:ещё |еще )?(?:обязательно )?пересекутся/i,
  /(?:сохраним|оставим|добавим|внес[её]м)[^.!?\n]{0,30}(?:кадров[а-яё]* резерв|в (?:нашей )?базе|в (?:нашу )?базу)/i,
];

// Метка статуса hh в чате. Когда работодатель переводит отклик в «Отказ», chatik рисует
// её отдельным сообщением («Отказ») или приклеивает к письму без пробела: «ЕленаОтказТимофей
// Игоревич, здравствуйте!» (имя рекрутера + метка + текст). Без флага i: «отказ» строчными
// в середине обычной фразы — не метка, а «Отказ от …» с пробелом после — тоже не она.
const HH_REJECTION_MARK_RE = /^\s*(?:[А-ЯЁA-Z][а-яёa-z]{1,20})?Отказ[.!]?(?:\s*$|\s*\n|(?=[А-ЯЁ]))/;

/** Похоже ли сообщение на отказ (метка hh или типовые формулировки). */
function looksLikeRejection(text) {
  const raw = String(text || '');
  return HH_REJECTION_MARK_RE.test(raw) || REJECTION_PATTERNS.some((re) => re.test(raw));
}

/** Текст сообщения без приклеенного имени отправителя («НаталияТимофей…» → «Тимофей…»). */
function messageBody(m) {
  const text = String((m && m.text) || '');
  const author = m && m.author;
  return author && text.startsWith(author) ? text.slice(author.length).trim() : text;
}

/** Сообщения работодателя после нашего последнего (то, на что слово за нами). */
function employerTail(messages) {
  const msgs = messages || [];
  let start = msgs.length;
  while (start > 0 && msgs[start - 1] && msgs[start - 1].from === 'employer') start -= 1;
  return msgs.slice(start);
}

/**
 * Есть ли отказ среди сообщений работодателя после нашего последнего. Отказ часто
 * приходит двумя сообщениями: письмо и метка hh «Отказ», или письмо и следом «Удачи!».
 * Раньше смотрели только на последнее сообщение — и если отказ был предпоследним, ИИ
 * отвечал на хвост как на обычную реплику. Если уже после отказа работодатель сам зовёт
 * на созвон или говорит о времени, это не отказ: решает человек (см. looksLikeScheduling).
 */
function rejectedInTail(messages) {
  const tail = employerTail(messages);
  let at = -1;
  tail.forEach((m, i) => { if (looksLikeRejection(m.text)) at = i; });
  if (at === -1) return false;
  return !tail.slice(at + 1).some((m) => looksLikeScheduling(m.text));
}

// Системные сообщения от "Службы заботы" hh.ru (не от самого работодателя!) о том, что
// работодатель проходит проверку/заблокирован и переписка с ним временно недоступна.
// Отвечать здесь буквально нечего и незачем: это ограничение самого hh.ru, а не вопрос
// от человека, которого можно было бы обсудить или на который можно повлиять. Раньше
// эти сообщения не отличались от обычной реплики работодателя и уходили в общий 'reply'
// (а дальше LLM иногда решала, что тут "важный факт" и заводила needsHuman) — жаловались,
// что это в принципе не должно попадать в "Нужен ваш ответ".
const HH_SYSTEM_UNAVAILABLE_PATTERNS = [
  /работодатель\s+(?:сейчас\s+)?(?:проходит|проходил)[^.!?\n]{0,60}(?:дополнительн\w*\s+)?провер\w*/i,
  /переписка\s+с\s+ним\s+(?:временно\s+)?недоступна/i,
  /работодатель\s+заблокирован\s+или\s+проходит\s+проверку/i,
];

/** Это системное сообщение hh.ru про блокировку/проверку работодателя, а не реплика человека? */
function looksLikeHhSystemUnavailable(text) {
  const raw = String(text || '');
  return HH_SYSTEM_UNAVAILABLE_PATTERNS.some((re) => re.test(raw));
}

// Вежливые автоответы «мы всё получили, ждите». Отвечать на них нечего: вопроса нет,
// а лишнее сообщение в треде только мешает рекрутеру.
const ACK_PATTERNS = [
  /рассмотрим ваше резюме/i,
  /(?:мы )?получили ваш отклик/i,
  /(?:если|как только)[^.]{0,60}(?:подойд|заинтересу)[^.]{0,40}(?:свяжемся|напишем)/i,
  /спасибо за (?:ваш )?отклик[^?]*$/i,
];

const QUESTION_HINTS = [
  /\?/,
  /расскажите|уточните|подскажите|напишите|заполните|пройдите|ответьте/i,
  /когда (?:вам )?удобно|готовы ли вы|интересно ли вам/i,
];

// Приглашение на созвон/интервью, ПОДТВЕРЖДЁННОЕ В ЧАТЕ (не статус вкладки hh, а живой
// текст: работодатель/его ИИ зовёт на собеседование или просит выбрать время созвона).
// Это точка «первичный этап пройден» — её выделяем как победу и передаём человеку.
// Формулировки специфичны, чтобы не срабатывать на «расскажите о себе»/«ждём резюме».
const INTERVIEW_INVITE_PATTERNS = [
  /пригла[шсc][аеё][а-я]*[^.!?\n]{0,40}(?:на )?(?:собесед|интервью|созвон|звонок|встреч|видеозвон|видеовстреч)/i,
  /(?:выбер|подбер|предлож|назнач|соглас|определ)[а-я]*[^.!?\n]{0,55}(?:врем|слот|дат[уые]|день|удобн)[^.!?\n]{0,55}(?:созвон|звонок|собесед|интервью|встреч|поговор|пообщ|call|колл)/i,
  /когда[^.!?\n]{0,30}(?:вам )?удобно[^.!?\n]{0,30}(?:созвон|поговор|пообщ|встрет|интервью|собесед|звонок|call|колл)/i,
  /(?:готов[ыа]|хотим|хотели бы|можем|рады|предлагаю|предлагаем)[^.!?\n]{0,30}(?:пригласить|позвать|предложить|провести)[^.!?\n]{0,35}(?:собесед|интервью|созвон|звонок|встреч|следующий этап|тех)/i,
  /(?:zoom\.us|meet\.google|teams\.(?:microsoft|live)|telemost|ktalk|контур\.?толк|jazz\.sber|whereby\.com)/i,
  /техническо[а-я]*[^.!?\n]{0,12}(?:интервью|собесед|секц|созвон|звонок)/i,
  /назнач[а-я]*[^.!?\n]{0,22}(?:созвон|звонок|интервью|собеседование|встреч)/i,
  /следующий этап[^.!?\n]{0,45}(?:созвон|звонок|интервью|собесед|встреч)/i,
  // «Предлагаю/давайте созвониться», «можем созвониться»
  /(?:предлаг|давай(?:те)?|можем|можете|готов[аы]|хочу|хотим|хотел[аи]? бы)[а-я]*[^.!?\n]{0,20}созвон/i,
  // «созвон … время/слот/когда удобно» и обратный порядок
  /созвон[а-я]*[^.!?\n]{0,45}(?:слот|врем|когда|удобн|календар)/i,
  /(?:слот|врем[яен]|когда|удобн|календар)[^.!?\n]{0,45}созвон/i,
  // «Ждём вас на собеседование/интервью»
  /жд[её]м вас[^.!?\n]{0,30}(?:на )?(?:собесед|интервью|созвон|встреч)/i,
];

/** Приглашают ли нас в этом сообщении на созвон/собеседование (подтверждено в чате). */
function detectInterviewInvite(text) {
  const raw = String(text || '');
  // ОТКАЗ — это НЕ приглашение, даже если в нём есть слова «пригласить»/«следующий этап»:
  // «мы НЕ можем пригласить вас на следующий этап» раньше ошибочно светилось «победой».
  if (looksLikeRejection(raw)) return false;
  // Прямая защита от отрицания рядом с приглашающим глаголом — на случай формулировки
  // отказа, которую паттерны выше не поймали: «не можем/не готовы/не будем … пригласить».
  if (/не\s+(?:можем|сможем|готов[ыа]|будем|станем|планиру[а-я]+|получится)[^.!?\n]{0,25}(?:пригласи|позва|предложи|провед|назнач)/i.test(raw)) {
    return false;
  }
  return INTERVIEW_INVITE_PATTERNS.some((re) => re.test(raw));
}

// «Робот-рекрутер» — скриптовый скрининг-бот hh.ru (не LLM и не человек): один вопрос за
// раз, простой парсер ответа. Живой тест на реальном чате показал: короткий прямой ответ
// ("На территории РФ") бот принимает и идёт дальше, а наш обычный стиль ответа (дисклеймер
// + вопрос про созвон в довесок) он не разбирает — переспрашивает по кругу и в итоге
// перезапускает весь опрос с начала. Отвечать такому боту нужно ТОЛЬКО фактом, без довеска.
// Имя бота hh показывает лишь у ПЕРВОГО сообщения серии (как у любого чата — подряд идущие
// сообщения одного отправителя имя не повторяют), поэтому по последнему сообщению бота не
// узнать: ищем фиксированный текст приветствия по ВСЕЙ истории треда — раз бот заходил,
// все следующие вопросы работодателя в этом треде тоже от него, пока не появится обычная
// человеческая реплика.
const SCREENER_BOT_INTRO_RE = /Чтобы работодатель узнал о вас больше[^.]*ответьте на несколько вопросов/i;

// Закрытый вопрос бота — ответ «да» или «нет»: «Есть ли у вас…?», «Готовы ли…?», «Вы готовы…?».
// Скрининг-бот на такие вопросы ждёт ровно «Да»/«Нет» (кнопками или текстом), а на
// развёрнутый ответ переспрашивает: по 46 тредам с ботом — 37 повторов, почти все на абзац
// в ответ на закрытый вопрос (06.10.2026). Смотрим последнее предложение с «?»: перед ним
// бывает пояснение («Работа в офисе в Кургане. Рассматриваете?»). «ли» — закрытый вопрос,
// даже если дальше есть «как» («Есть ли красный диплом, как описано в вакансии?»).
// Вопрос с «или» — выбор из вариантов, не «да/нет».
const OPEN_START_RE = /^(?:а |и |подскажите,? |скажите,? )?(?:как|где|сколько|когда|почему|зачем|кто|что|чем|куда|откуда|опишите|расскажите|укажите|назовите|перечислите|напишите|пришлите)/i;
const CLOSED_START_RE = /^(?:а |и )?(?:(?:вы|ты|вам|тебе|есть|у вас|у тебя)(?![а-яё])|был|готов|согласн|имеете|имеется|рассматрива|планируете|можете|сможете|работали|работаете|владеете|используете|знакомы|обучаетесь|учитесь)/i;

/** Закрытый вопрос (ответ — «да» или «нет»)? */
function looksLikeClosedQuestion(text) {
  const q = (String(text || '').match(/[^.!?\n]*\?/g) || []).pop();
  if (!q) return false;
  const s = q.trim();
  if (/(?:^|[^а-яё])или(?![а-яё])/i.test(s)) return false;
  if (/(?:^|[^а-яё])ли(?![а-яё])/i.test(s)) return true;
  if (OPEN_START_RE.test(s)) return false;
  return CLOSED_START_RE.test(s);
}

/** Шёл ли в этом треде скриптовый скрининг-бот hh (а не живой человек)? */
function isScreenerBotThread(messages) {
  return (messages || []).some((m) => m.from === 'employer' && SCREENER_BOT_INTRO_RE.test(m.text));
}

// Разговор о времени созвона — решает ТОЛЬКО сам кандидат, ИИ на такие сообщения не отвечает
// вообще. Живой случай: автопилот сам согласился на «сегодня в 19:00» и придумал кандидату
// «в будни после 15:00». Цена промаха несимметрична: лишний раз отдать человеку — пара минут
// его внимания, а созвон, о котором он не знает, — сорванное собеседование. Поэтому ловим
// широко: приглашение (detectInterviewInvite), конкретное время в связке со встречей или с
// вопросом «удобно/подойдёт», вопрос «когда/во сколько вам удобно». «С понедельника сможете
// выйти?» тоже попадёт сюда — и правильно: дата выхода тоже решение человека.
// День недели — только с предлогом: иначе «какие среды разработки используете?» читалось
// как разговор о среде-дне.
const DAY_WORD = '(?:^|[^а-яё])(?:сегодня|завтра|послезавтра)(?![а-яё])';
const WEEKDAY = '(?:^|[^а-яё])(?:в|во|на|до|к|с|со|по)\\s+(?:понедельник|вторник|сред|четверг|пятниц|суббот|воскресень)[а-яё]*';
const CLOCK = '(?:^|[^\\d])\\d{1,2}:\\d{2}(?!\\d)';
const TIME_REF = new RegExp([
  DAY_WORD,
  WEEKDAY,
  CLOCK,
  'на (?:этой|следующей|той) неделе',
  // С точкой («в 15.00») — только в связке со словами о встрече ниже: иначе это номер
  // версии («Node.js 18.20», «Python 3.11»).
  '(?:^|[^\\d])\\d{1,2}\\.\\d{2}(?!\\d)',
  '(?:^|[^а-яё])в \\d{1,2}(?:\\s*(?:час|ч\\.|утра|вечера|дня))?(?![\\d:.])',
  '\\d{1,2} (?:январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)',
  'по (?:мск|москве)',
].join('|'), 'i');
// Вопрос с конкретным днём или временем — уже разговор о времени, без слов-подсказок.
// Живой промах: «Завтра с 9:00 до 12:00 есть возможность?» — ни «созвона», ни «удобно»,
// и ИИ ответил за человека.
const DAY_OR_CLOCK = new RegExp([DAY_WORD, WEEKDAY, CLOCK].join('|'), 'i');
const MEET_WORD = /созвон|звон|встреч|интервью|собесед|zoom|зум|телемост|meet|teams|видеосвяз|call|колл|поговор|пообща|слот/i;
const AVAIL_WORD = /удобн|подойд[её]т|подходит|сможете|получится|свободн|успеете|можете|можем|давайте|предлага|назнач|перенес|перенос|возможност|актуальн|в силе|доступн/i;
const WHEN_ASK = /(?:какое время|во сколько|когда|в какое время|какой день|какие дни)[^.!?\n]{0,40}(?:удобн|свободн|сможете|получится|подойд|подходит|возможност)/i;

/** Идёт ли речь о времени созвона/собеседования — тогда отвечает только человек. */
function looksLikeScheduling(text) {
  const raw = String(text || '');
  if (detectInterviewInvite(raw)) return true;
  if (WHEN_ASK.test(raw)) return true;
  if (DAY_OR_CLOCK.test(raw) && raw.includes('?')) return true;
  return TIME_REF.test(raw) && (MEET_WORD.test(raw) || AVAIL_WORD.test(raw));
}

// Работодатель заподозрил, что ему отвечает не человек («это ИИ сообщение, не совсем поняла
// Вас»). Любой автоматический ответ здесь только вредит: живой случай — модель в ответ
// выдумала «технический сбой с шаблонами автоответов». Такое сообщение уходит человеку.
// Шаблоны узкие намеренно: кандидат — AI/LLM-инженер, и работодатели постоянно пишут ему
// про ИИ, нейросети и ботов ПО ДЕЛУ («опыт с ИИ?», «вы ИИ-инженер?», «делаем чат-бота»).
// Ловим только подозрение, что ИИ пишет САМИ СООБЩЕНИЯ.
const AI_WORD = '(?:ии|ai|gpt|chatgpt|нейросет[а-яё]*|бот[а-яё]*|робот[а-яё]*)';
const AI_SUSPICION_PATTERNS = [
  // «это ИИ сообщение», «такой AI-ответ»
  new RegExp(`(?:это|такое|такой|ваше|ваш|твоё|твое)\\s+(?:[а-яё]+\\s+)?${AI_WORD}[\\s-]*(?:сообщени|ответ|текст|письм)`, 'i'),
  // «сообщение написано нейросетью», «ответ сгенерирован ИИ»
  new RegExp(`(?:сообщени|ответ|текст|письм)[а-яё]*\\s+(?:[а-яё]+\\s+){0,2}(?:написан|сгенерирован|составлен|создан)[а-яё]*\\s+(?:[а-яё]+\\s+)?${AI_WORD}(?![а-яёa-z-])`, 'i'),
  // «вы бот?», «ты нейросеть?» — но не «вы ИИ-инженер»
  new RegExp(`(?:^|[^а-яё])(?:вы|ты)\\s+(?:[—-]\\s+)?(?:бот|робот|нейросеть|ии|ai|chatgpt)(?![а-яёa-z-])`, 'i'),
  // «мне отвечает нейросеть», «пишете через ИИ»
  new RegExp(`(?:отвеча|пиш|переписыва|общаю)[а-яё]*\\s+(?:[а-яё]+\\s+){0,2}${AI_WORD}(?![а-яёa-z-])`, 'i'),
];
// Короткая реплика про ИИ «тут» — ирония после того, как автопилот выдал себя. Живой
// случай: «ИИ интересно тут работает 😜» в ответ на ушедшее в чат «Вы исчерпали лимит на
// ответы от ИИ». Только для коротких сообщений (до 60 символов): в более длинных работодатели рассказывают про
// свой ИИ-продукт, и это вопрос по делу.
const AI_HERE = new RegExp(`(?<![а-яёa-z])${AI_WORD}(?![а-яёa-z-])[^.!?\\n]{0,30}(?:тут|здесь|у вас|работает|отвечает|пишет)|(?:тут|здесь|у вас)[^.!?\\n]{0,20}(?<![а-яёa-z])${AI_WORD}(?![а-яёa-z-])`, 'i');

/** Подозревает ли работодатель, что ему пишет ИИ, а не кандидат. */
function looksLikeAiSuspicion(text) {
  const raw = String(text || '');
  if (raw.trim().length <= 60 && AI_HERE.test(raw)) return true;
  return AI_SUSPICION_PATTERNS.some((re) => re.test(raw));
}

const URL_RE = /https?:\/\/[^\s<>"')]+|(?:^|\s)(?:t\.me|telegram\.me)\/[A-Za-z0-9_+/-]+/gi;

/** Ссылки из сообщения — по ним работодатель гонит на внешний этап. */
function extractLinks(text) {
  const found = String(text || '').match(URL_RE) || [];
  return [...new Set(found.map((u) => {
    const trimmed = u.trim().replace(/[.,;)]+$/, '');
    return /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
  }))];
}

/**
 * @returns {{ kind: 'rejection'|'hh_unavailable'|'ack'|'external_stage'|'reply', links: string[], why: string }}
 */
function classifyEmployerMessage(text) {
  const raw = String(text || '').trim();
  const links = extractLinks(raw);

  if (looksLikeHhSystemUnavailable(raw)) {
    return { kind: 'hh_unavailable', links, why: 'системное сообщение hh.ru — работодатель заблокирован/на проверке' };
  }

  if (looksLikeRejection(raw)) return { kind: 'rejection', links, why: 'отказ по формулировке' };

  // Ссылка сильнее вежливой заглушки: «спасибо за отклик, заполните анкету» — это этап,
  // а не отписка.
  if (links.length) return { kind: 'external_stage', links, why: 'в сообщении есть ссылка' };

  const hasQuestion = QUESTION_HINTS.some((re) => re.test(raw));
  if (!hasQuestion) {
    for (const re of ACK_PATTERNS) {
      if (re.test(raw)) return { kind: 'ack', links, why: 'автоответ без вопроса' };
    }
  }

  return { kind: 'reply', links, why: 'обычное сообщение' };
}

