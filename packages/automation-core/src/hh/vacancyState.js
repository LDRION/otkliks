/**
 * vacancyState.js — распознавание «вакансия закрыта/архивная» по тексту страницы.
 *
 * Это свойство вакансии, а не поломка селектора: ни кнопки отклика, ни поля ввода в
 * чате там нет ЗАКОНОМЕРНО и не появится, сколько ни ретрай. Общий регэксп для двух
 * мест, которые на это натыкаются по-разному — отклик (apply.js) и ответ в чате
 * (negotiations.js) — чтобы не разъезжались форматулировки и не дублировались.
 */

const CLOSED_VACANCY_RE = /вакансия (в архиве|заверш|закрыт)|приём (заявок|откликов) (завершён|закрыт)|больше не актуальна/i;

// Чат закрыт для переписки — по ДРУГИМ причинам, чем архивная вакансия: работодатель
// явно выключил переписку по вакансии, или после отказа hh сам закрывает чат до нового
// приглашения. Живой случай: composer пропадал НЕ из-за архивной вакансии (вакансия
// вполне активна), а именно из-за этого — CLOSED_VACANCY_RE его не ловил, и отправка
// ретраилась 3 раза как "вёрстка сломалась", хотя писать было физически некуда.
const CHAT_CLOSED_RE = /работодатель отключил переписку|переписка будет доступна после приглашения/i;

module.exports = { CLOSED_VACANCY_RE, CHAT_CLOSED_RE };
