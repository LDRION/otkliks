// Контакт для связи — ТОЛЬКО из явного поля профиля. Живой случай: работодатель написал
// «свяжемся с вами здесь или в тг», поля не было — и модель выдала за Telegram кандидата
// @AI_ConstructorBot, одного из его проектов из резюме. Ники, боты, каналы и ссылки в
// резюме — это проекты, не контакты; угадывать контакт нельзя никогда.
function normalizeTelegram(v) {
  const s = String(v || '').trim().replace(/^https?:\/\/(?:t|telegram)\.me\//i, '').replace(/^@/, '');
  return /^[A-Za-z0-9_]{5,32}$/.test(s) ? `@${s}` : '';
}

function contactRule(profile) {
  const tg = normalizeTelegram(profile && profile.contactTelegram);
  return `КОНТАКТЫ — ЖЁСТКОЕ ПРАВИЛО:
${tg
  ? `- Единственный контакт, который можно назвать: Telegram ${tg}. Называй его ТОЛЬКО если работодатель
  сам просит контакт или предлагает продолжить в мессенджере — не вставляй его в каждое сообщение.`
  : `- Контакта для связи в профиле нет. Если работодатель просит контакт или предлагает мессенджер —
  ответь, что удобно продолжить здесь, в чате hh.ru. НЕ называй никаких ников, номеров и адресов.`}
- НИКОГДА не выдавай за контакт кандидата ники, @-упоминания, ботов, каналы, сайты и ссылки из
  резюме или истории переписки — это проекты и работы кандидата, а не способ с ним связаться.
- Телефон и почту не называй вовсе: работодатель видит их в резюме на hh.ru.`;
}

